/* Generates src/ui/worldmap.data.ts — the country outlines the WorldMap
   component draws. Run it only when the geometry itself must change; the
   output is committed so the app carries no map dependency at all.

     npm i --no-save world-atlas topojson-client d3-geo i18n-iso-countries
     node scripts/gen-worldmap.mjs

   Source: Natural Earth 1:110m (public domain) via world-atlas (ISC).
   Shapes are projected here, at build time, so the runtime needs no
   projection maths: it just paints the `d` strings. */

import { writeFileSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoEqualEarth, geoPath } from 'd3-geo'
import iso from 'i18n-iso-countries'

const require = createRequire(import.meta.url)
const WIDTH = 800

