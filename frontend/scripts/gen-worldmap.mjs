/* NE ships a few shapes with no ISO numeric id; these are the ones worth keeping. */
const BY_NAME = { Kosovo: 'XK', 'N. Cyprus': null, Somaliland: null }

const atlas = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8')
)
const fc = feature(atlas, atlas.objects.countries)
const shapes = fc.features.filter((f) => f.properties.name !== 'Antarctica')

const projection = geoEqualEarth().fitWidth(WIDTH, { type: 'FeatureCollection', features: shapes })
const path = geoPath(projection)
const [[x0, y0], [x1, y1]] = path.bounds({ type: 'FeatureCollection', features: shapes })
/* Re-centre so the drawing starts at 0,0 and the viewBox has no dead margin. */
const t = projection.translate()
projection.translate([t[0] - x0, t[1] - y0])
const HEIGHT = Math.ceil(y1 - y0)

const n1 = (v) => String(Math.round(v * 10) / 10)
const join = (x, y) => `${n1(x)}${y < 0 ? '' : ','}${n1(y)}`

/* d3 emits absolute L commands with full precision. Rounding to a tenth of a
   viewBox unit (~0.1px at the size this renders) and switching to relative
   line-tos roughly halves the file, with no visible difference. Deltas are
   taken between already-rounded points, so the error cannot accumulate. */
function compact(d) {
  let out = ''
  for (const sub of d.split('M').filter(Boolean)) {
    const closed = sub.endsWith('Z')
    const pts = (closed ? sub.slice(0, -1) : sub)
      .split('L')
      .map((p) => p.split(',').map((v) => Math.round(Number(v) * 10) / 10))
    let [px, py] = pts[0]
    out += `M${join(px, py)}`
    for (let i = 1; i < pts.length; i++) {
      const [x, y] = pts[i]
      if (x === px && y === py) continue
      out += `l${join(x - px, y - py)}`
      px = x
      py = y
    }
    if (closed) out += 'Z'
  }
  return out
}

const paths = {}
const skipped = []
for (const f of shapes) {
  const code = f.id ? iso.numericToAlpha2(f.id) : BY_NAME[f.properties.name] ?? null
  if (!code) {
    skipped.push(f.properties.name)
    continue
  }
  const d = compact(path(f))
  paths[code] = paths[code] ? paths[code] + d : d
}

const dots = {}
for (const [code, lonlat] of Object.entries(DOTS)) {
  if (paths[code]) continue
  const p = projection(lonlat)
  if (p) dots[code] = [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10]
}

const entries = (o, fmt) =>
  Object.keys(o).sort().map((k) => `  ${k}: ${fmt(o[k])},`).join('\n')

writeFileSync(
  new URL('../src/ui/worldmap.data.ts', import.meta.url),
  `/* GENERATED by scripts/gen-worldmap.mjs — do not edit by hand.
   Natural Earth 1:110m (public domain), projected with Equal Earth. */

export const WORLD_WIDTH = ${WIDTH}
export const WORLD_HEIGHT = ${HEIGHT}

/** Country outline by ISO 3166-1 alpha-2 code, already projected. */
export const WORLD_PATHS: Record<string, string> = {
${entries(paths, (v) => JSON.stringify(v))}
}

/** Countries too small to draw at this scale: projected marker position. */
export const WORLD_DOTS: Record<string, [number, number]> = {
${entries(dots, (v) => `[${v[0]}, ${v[1]}]`)}
}
`
)

console.log(`viewBox 0 0 ${WIDTH} ${HEIGHT}`)
console.log(`${Object.keys(paths).length} outlines, ${Object.keys(dots).length} dots`)
if (skipped.length) console.log('no ISO code, skipped:', skipped.join(', '))
